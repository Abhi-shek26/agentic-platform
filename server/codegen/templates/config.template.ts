/** App shell with tab nav over generated pages (no router dep required). */
export const appTsxTemplate = (appTitle: string, pages: EntryPageRef[]): string => {
  const imports = pages.map((p) => `import ${p.alias} from './pages/${p.fileBase}';`).join('\n');
  const buttons = pages
    .map((p, i) => `        <button
          key="${p.alias}"
          onClick={() => setActive(${i})}
          className={\`px-4 py-2 rounded-lg font-medium \` + (active === ${i} ? 'bg-blue-600 text-white' : 'text-gray-600 hover:bg-gray-100')}
        >
          ${p.name}
        </button>`)
    .join('\n');
  const cases = pages.map((p, i) => `      case ${i}: return <${p.alias} />;`).join('\n');
  const safeTitle = appTitle.replace(/</g, '&lt;').replace(/'/g, "\\'");
  return `import React, { useState } from 'react';
${imports}

export default function App() {
  const [active, setActive] = useState(0);

  const renderPage = () => {
    switch (active) {
${cases}
      default: return ${pages.length > 0 ? `<${pages[0].alias} />` : '<div />'};
    }
  };

  return (
    <div className="min-h-screen bg-gray-50">
      <nav className="bg-white shadow">
        <div className="max-w-7xl mx-auto px-4 py-4 flex flex-wrap gap-2 items-center">
          <span className="text-xl font-bold text-blue-600 mr-4">${safeTitle}</span>
${buttons}
        </div>
      </nav>
      <main>{renderPage()}</main>
    </div>
  );
}
`;
};

/** Minimal Express entry that mounts generated routes + serves the vite build. */
export const serverIndexTemplate = (): string => `import express from 'express';
import path from 'path';
import router from './routes/index';

const app = express();
const PORT = Number(process.env.PORT || 5000);

app.use(express.json());
app.use((req, res, next) => {
  res.header('Access-Control-Allow-Origin', '*');
  res.header('Access-Control-Allow-Methods', 'GET, POST, PUT, DELETE, OPTIONS');
  res.header('Access-Control-Allow-Headers', 'Content-Type, Authorization');
  if (req.method === 'OPTIONS') return res.sendStatus(200);
  next();
});

app.get('/health', (_req, res) => res.json({ status: 'ok' }));

// Generated routes already carry the /api prefix (e.g. router.get('/api/...'))
app.use('/', router);

const distPath = path.resolve(process.cwd(), 'dist/client');
app.use(express.static(distPath));
app.get('*', (_req, res) => {
  res.sendFile(path.join(distPath, 'index.html'), (err) => {
    if (err) res.status(404).json({ error: 'Not found — run npm run build first' });
  });
});

app.listen(PORT, '0.0.0.0', () => {
  console.log(\`Server running at http://localhost:\${PORT}\`);
});

export default app;
`;

