/** Sanitize a page name into a safe TS identifier + file basename. */
export const pageFileBase = (name: string): string =>
  String(name || 'page').toLowerCase().replace(/\s+/g, '-').replace(/[^a-z0-9-_]/g, '') || 'page';

export const pageComponentAlias = (name: string, index: number): string => {
  const cleaned = String(name || `Page${index}`).replace(/[^a-zA-Z0-9]/g, '') || `Page${index}`;
  const pascal = cleaned.charAt(0).toUpperCase() + cleaned.slice(1);
  return `Page_${/^[A-Za-z_$]/.test(pascal) ? pascal : `P${index}_${pascal}`}`;
};

